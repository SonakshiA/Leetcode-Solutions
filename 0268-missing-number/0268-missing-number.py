class Solution(object):
    def missingNumber(self, nums):
        """
        :type nums: List[int]
        :rtype: int
        """
        n = len(nums)
        sum_actual = sum(nums)
        sum_ap = n*(n+1)//2

        return sum_ap - sum_actual

